import { describe, expect, it, vi } from 'vitest';
import { YoutubeDataLibraryProvider } from '../src/infrastructure/youtube/youtube-data-library-provider.js';

const context = {
  access: 'fixture-access',
  signal: new AbortController().signal,
};
const film = 'aaaaaaaaaaa',
  clip = 'bbbbbbbbbbb',
  track = 'ccccccccccc',
  course = 'ddddddddddd',
  privateId = 'eeeeeeeeeee',
  unavailable = 'fffffffffff';
const musicType = 'MUSIC_VIDEO_TYPE_';
const video = (id: string, title: string, privacyStatus = 'public') => ({
  id,
  snippet: {
    title,
    categoryId: '10',
    channelTitle: 'Autor',
    description:
      id === track
        ? 'Provided to YouTube by Label\nAuto-generated by YouTube.'
        : '',
  },
  contentDetails: { duration: 'PT42S' },
  status: { privacyStatus, uploadStatus: 'processed' },
});
function panel(id: string, type: string, endpointId = id, playable = true) {
  return {
    playlistPanelVideoRenderer: {
      videoId: id,
      ...(!playable && { unplayableText: { simpleText: 'Indisponible' } }),
      navigationEndpoint: {
        watchEndpoint: {
          videoId: endpointId,
          watchEndpointMusicSupportedConfigs: {
            watchEndpointMusicConfig: { musicVideoType: musicType + type },
          },
        },
      },
    },
  };
}
const page = {
  items: [
    video(film, 'Una escena de una película'),
    video(clip, 'Videoclip'),
    video(track, 'Grabación corta'),
    video(course, 'Curso'),
    video(privateId, 'Privado', 'private'),
    video(unavailable, 'Sin disponibilidad en Music'),
  ],
};

describe('grabaciones en la biblioteca del canal', () => {
  it('comprueba IDs exactos por lote y mantiene los videoclips y las canciones cortas', async () => {
    const fetcher = vi
      .fn<typeof fetch>()
      .mockResolvedValueOnce(Response.json(page))
      .mockResolvedValueOnce(
        Response.json({
          queueDatas: [
            {
              content: {
                playlistPanelVideoWrapperRenderer: {
                  primaryRenderer: panel(film, 'UGC'),
                  counterpart: [
                    { counterpartRenderer: panel('zzzzzzzzzzz', 'ATV') },
                  ],
                },
              },
            },
            { content: panel(clip, 'OMV') },
            { content: panel(course, 'ATV', 'zzzzzzzzzzz') },
            { content: panel(unavailable, 'ATV', unavailable, false) },
          ],
        }),
      );
    const provider = new YoutubeDataLibraryProvider(fetcher, {
      verifyMusic: true,
    });
    const liked = await provider.listLikedVideos(context, { maxResults: 50 });
    expect(liked.items.filter((v) => v.isRecording).map((v) => v.id)).toEqual([
      clip,
      track,
    ]);
    const [url, init] = fetcher.mock.calls[1]!;
    expect(new URL(String(url)).pathname).toBe('/youtubei/v1/music/get_queue');
    expect(JSON.parse(String(init?.body)).videoIds).toEqual([
      film,
      clip,
      course,
      unavailable,
    ]);
    expect(new Headers(init?.headers).has('Authorization')).toBe(false);
    expect(init?.credentials).toBe('omit');
    fetcher.mockResolvedValueOnce(
      Response.json({ items: [video(film, 'Peli'), video(clip, 'Videoclip')] }),
    );
    const again = await provider.getVideos(context, [film, clip]);
    expect(again.map((v) => v.isRecording)).toEqual([false, true]);
    expect(fetcher).toHaveBeenCalledTimes(3);
  });

  it('conserva los Art Tracks y reintenta los candidatos si Music falló en una consulta anterior', async () => {
    const raw = {
      items: [video(track, 'Grabación'), video(clip, 'Videoclip')],
    };
    const fetcher = vi
      .fn<typeof fetch>()
      .mockResolvedValueOnce(Response.json(raw))
      .mockResolvedValueOnce(new Response(null, { status: 503 }))
      .mockResolvedValueOnce(Response.json(raw))
      .mockResolvedValueOnce(
        Response.json({ queueDatas: [{ content: panel(clip, 'OMV') }] }),
      );
    const provider = new YoutubeDataLibraryProvider(fetcher, {
      verifyMusic: true,
    });
    expect(
      (await provider.getVideos(context, [track, clip])).map(
        (v) => v.isRecording,
      ),
    ).toEqual([true, false]);
    expect(
      (await provider.getVideos(context, [track, clip])).map(
        (v) => v.isRecording,
      ),
    ).toEqual([true, true]);
  });
});
